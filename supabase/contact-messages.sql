-- Execute no SQL Editor do Supabase para habilitar a caixa de entrada.
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  subject text not null check (char_length(subject) between 1 and 160),
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now(),
  replied_at timestamptz
);

alter table public.contact_messages enable row level security;

-- Visitantes podem enviar mensagens, mas não podem ler nem alterar a caixa de entrada.
drop policy if exists "Public can submit contact messages" on public.contact_messages;
create policy "Public can submit contact messages"
  on public.contact_messages for insert to anon, authenticated
  with check (true);

-- Somente usuários cadastrados como administradores podem consultar e atualizar mensagens.
drop policy if exists "Admins can read contact messages" on public.contact_messages;
create policy "Admins can read contact messages"
  on public.contact_messages for select to authenticated
  using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can update contact messages" on public.contact_messages;
create policy "Admins can update contact messages"
  on public.contact_messages for update to authenticated
  using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

create index if not exists contact_messages_created_at_idx
  on public.contact_messages (created_at desc);
